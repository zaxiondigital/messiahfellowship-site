# Optimise photos for the web using Windows' built-in System.Drawing (no installs).
# - Opaque PNG photos  -> JPEG (quality 80), max 1600px wide, same name with .jpg
# - Large JPEGs        -> re-encoded at quality 80, max 1600px wide
# - PNGs with transparency, small files (<80 KB), icons and logos are left alone
# Writes tools/image-map.txt (old -> new) for updating page references.
param(
  [string]$Root = (Split-Path $PSScriptRoot -Parent),
  [int]$MaxWidth = 1600,
  [long]$Quality = 80,
  [int]$MinBytes = 80KB,
  [switch]$DryRun
)
Add-Type -AssemblyName System.Drawing
$imgDir = Join-Path $Root 'images'
$codec  = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
$params = New-Object System.Drawing.Imaging.EncoderParameters 1
$params.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality), $Quality

# Returns 'opaque', 'corners:<radiusPx>' (transparency only in rounded corners) or 'transparent'
function Get-Transparency([System.Drawing.Bitmap]$bmp) {
  if (-not [System.Drawing.Image]::IsAlphaPixelFormat($bmp.PixelFormat)) { return 'opaque' }
  $W = $bmp.Width; $H = $bmp.Height
  $rect = New-Object System.Drawing.Rectangle 0, 0, $W, $H
  $data = $bmp.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
  try {
    $stride = $data.Stride
    $bytes = New-Object byte[] ($stride * $H)
    [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $bytes, 0, $bytes.Length)
    $corner = [int]([math]::Min($W, $H) * 0.15)
    $any = $false
    for ($y = 0; $y -lt $H; $y++) {
      $row = $y * $stride
      for ($x = 0; $x -lt $W; $x++) {
        if ($bytes[$row + $x * 4 + 3] -lt 250) {
          $any = $true
          $inCorner = (($x -lt $corner) -or ($x -ge $W - $corner)) -and (($y -lt $corner) -or ($y -ge $H - $corner))
          if (-not $inCorner) { return 'transparent' }
        }
      }
    }
    if (-not $any) { return 'opaque' }
    # radius = transparent run along the top row from the left edge
    $r = 0; while ($r -lt $corner -and $bytes[$r * 4 + 3] -lt 250) { $r++ }
    return "corners:$r"
  } finally { $bmp.UnlockBits($data) }
}

$map = @(); $rounded = @(); $before = 0; $after = 0
Get-ChildItem $imgDir -File | Where-Object { $_.Extension -match '^\.(png|jpe?g)$' -and $_.Length -ge $MinBytes -and $_.Name -notmatch '^(logo|signature)' } | ForEach-Object {
  $f = $_
  $bmp = New-Object System.Drawing.Bitmap $f.FullName
  try {
    $kind = if ($f.Extension -eq '.png') { Get-Transparency $bmp } else { 'opaque' }
    if ($kind -eq 'transparent') { Write-Output ("keep  {0,-34} transparent" -f $f.Name); return }
    $w = $bmp.Width; $h = $bmp.Height
    if ($kind -like 'corners:*') {
      $r = [int]($kind -split ':')[1]
      # elliptical % radius so the CSS corner matches the baked one at any display size
      $rounded += ('img[src$="/{0}"] {{ border-radius: {1:0.##}% / {2:0.##}% !important; }}' -f ([IO.Path]::GetFileNameWithoutExtension($f.Name) + '.jpg'), (100 * $r / $w), (100 * $r / $h))
    }
    if ($w -gt $MaxWidth) { $nw = $MaxWidth; $nh = [int][math]::Round($h * $MaxWidth / $w) } else { $nw = $w; $nh = $h }
    $out = New-Object System.Drawing.Bitmap $nw, $nh
    $g = [System.Drawing.Graphics]::FromImage($out)
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
    $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $g.Clear([System.Drawing.Color]::White)
    $g.DrawImage($bmp, 0, 0, $nw, $nh)
    $g.Dispose()
    $newName = [IO.Path]::GetFileNameWithoutExtension($f.Name) + '.jpg'
    $tmp = Join-Path $imgDir ($newName + '.tmp')
    $out.Save($tmp, $codec, $params); $out.Dispose()
  } finally { $bmp.Dispose() }
  $newSize = (Get-Item $tmp).Length
  if ($f.Extension -ne '.png' -and $newSize -ge $f.Length) { Remove-Item $tmp; Write-Output ("keep  {0,-34} already small" -f $f.Name); return }
  $before += $f.Length; $after += $newSize
  Write-Output ("{0,-5} {1,-34} {2,7:N0} KB -> {3,6:N0} KB  {4}x{5}->{6}x{7}" -f 'jpg', $f.Name, ($f.Length/1KB), ($newSize/1KB), $w, $h, $nw, $nh)
  if ($DryRun) { Remove-Item $tmp; return }
  $target = Join-Path $imgDir $newName
  if ($f.Extension -eq '.png') { Remove-Item $f.FullName; $map += "$($f.Name) $newName" }
  if (Test-Path $target) { Remove-Item $target }
  Move-Item $tmp $target
}
if (-not $DryRun -and $map.Count) { $map | Out-File -Encoding utf8 (Join-Path $Root 'tools\image-map.txt') }
if (-not $DryRun -and $rounded.Count) {
  @('/* Generated by tools/optimize-images.ps1 – these photos had rounded corners baked into a',
    '   transparent PNG; as JPEGs the same corners are drawn with CSS (same radius, any size). */') + $rounded |
    Out-File -Encoding utf8 (Join-Path $Root 'images-rounded.css')
}
"`nTotal: {0:N1} MB -> {1:N1} MB" -f ($before/1MB), ($after/1MB)
